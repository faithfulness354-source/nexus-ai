import 'server-only';
import { PutObjectCommand, GetObjectCommand, DeleteObjectCommand } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import { createS3Client, getBucketConfig } from './aws-config';

function shouldServeInline(contentType: string): boolean {
  // image/svg+xml excluded — SVGs can execute embedded scripts (XSS risk)
  return (contentType.startsWith('image/') && contentType !== 'image/svg+xml')
    || contentType.startsWith('video/')
    || contentType.startsWith('audio/');
}

const s3 = createS3Client();

function safeName(fileName: string): string {
  return fileName.replace(/[^a-zA-Z0-9._-]+/g, '-').slice(-80) || 'file';
}

export async function generatePresignedUploadUrl(fileName: string, contentType: string, isPublic = false) {
  const { bucketName, folderPrefix } = getBucketConfig();
  const cloud_storage_path = `${folderPrefix}${isPublic ? 'public/' : ''}uploads/${Date.now()}-${safeName(fileName)}`;
  const uploadUrl = await getSignedUrl(
    s3,
    new PutObjectCommand({ Bucket: bucketName, Key: cloud_storage_path, ContentType: contentType }),
    { expiresIn: 3600 },
  );
  return { uploadUrl, cloud_storage_path };
}

/** Server-side upload of generated bytes (e.g. rendered scene images). */
export async function uploadBuffer(folder: string, fileName: string, body: Buffer, contentType: string, isPublic = true) {
  const { bucketName, folderPrefix } = getBucketConfig();
  const cloud_storage_path = `${folderPrefix}${isPublic ? 'public/' : ''}${folder}/${Date.now()}-${safeName(fileName)}`;
  await s3.send(new PutObjectCommand({ Bucket: bucketName, Key: cloud_storage_path, Body: body, ContentType: contentType }));
  return cloud_storage_path;
}

export async function getFileUrl(cloud_storage_path: string, contentType: string, isPublic: boolean) {
  const { bucketName } = getBucketConfig();
  if (isPublic) {
    const region = process.env.AWS_REGION ?? 'us-east-1';
    return `https://${bucketName}.s3.${region}.amazonaws.com/${cloud_storage_path.split('/').map(encodeURIComponent).join('/')}`;
  }
  return getSignedUrl(
    s3,
    new GetObjectCommand({
      Bucket: bucketName,
      Key: cloud_storage_path,
      ResponseContentDisposition: shouldServeInline(contentType) ? 'inline' : 'attachment',
    }),
    { expiresIn: 3600 },
  );
}

export async function deleteFile(cloud_storage_path: string) {
  const { bucketName } = getBucketConfig();
  await s3.send(new DeleteObjectCommand({ Bucket: bucketName, Key: cloud_storage_path }));
}
